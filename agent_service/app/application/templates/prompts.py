def sprint_prompt(spec: TemplateSpec, order: int, used_titles: list[str]) -> str:
    arc = _arc(spec.sprints)
    taken = ", ".join(used_titles) if used_titles else "пока ничего"
    first = order == 1
    header = (
        "Собери первый спринт учебного проекта и придумай название самого проекта."
        if first
        else f"Собери спринт {order} того же проекта."
    )
    extra = (
        '  "title": "Название проекта",\n  "description": "2-3 предложения о проекте",\n'
        if first
        else ""
    )
    return f"""{header}

Тема проекта: {spec.topic}
Направление: {spec.direction}, уровень: {spec.level}
Спринтов всего: {spec.sprints}, в этом спринте задач: {spec.tasks_per_sprint}
Этот спринт по сложности: {arc[order - 1] if order <= len(arc) else 'продвинутый'}
{('Заметки заказчика: ' + spec.notes) if spec.notes else ''}

Названия задач, которые уже заняты: {taken}. Не повторяй их и не пересказывай
те же задачи другими словами.

Верни объект JSON такого вида:
{{
{extra}  "sprint": {{
    "title": "Название спринта",
    "tasks": [{TASK_SHAPE}]
  }}
}}

Задач в массиве ровно {spec.tasks_per_sprint}.
{'Поле tests, reference и broken обязательны у каждой задачи.' if spec.with_tests else 'Поля tests, reference и broken можно оставить пустыми строками.'}"""


def repair_prompt(task: DraftTask, issues: list[CheckIssue]) -> str:
    problems = "\n".join(f"- {issue.message}" for issue in issues)
    payload = json.dumps(
        {
            "title": task.title,
            "description": task.description,
            "tests": task.tests,
            "reference": task.reference,
            "broken": task.broken,
        },
        ensure_ascii=False,
        indent=2,
    )
    return f"""Проверка нашла в задаче проблемы:
{problems}

Вот задача целиком:
{payload}

Почини ровно эти проблемы, остальное не трогай: тема, сигнатура и смысл задачи
остаются прежними. Если падает эталонное решение — виноват либо тест, либо
эталон, реши что именно и исправь. Если сломанное решение проходит все тесты,
добавь тест, который ловит эту ошибку.

Верни один объект JSON:
{TASK_SHAPE}

Поле description можно вернуть целиком вместо brief/rules/criteria, если
правок в тексте не требуется."""


def _arc(sprints: int) -> list[str]:
    ladder = [
        "базовый: функции, списки и словари, проверка аргументов",
        "средний: работа с SQLite, классы, разбор и валидация данных",
        "продвинутый: ошибки и повторы, идемпотентность, кэш, права доступа",
        "продвинутый: производительность, большие объёмы, аккуратные структуры",
        "итоговый: задачи на стыке тем, где важны и корректность, и читаемость",
    ]
    if sprints <= 1:
        return [ladder[0]]
    return ladder[:sprints]
